"""Extract the values of data symbols the game imports from the SDK module (nn::util constants and
tables, nn::hid ids, C++ ABI data, ...) out of the real `sdk` binary, and emit them as C arrays in sdkdata.c.

MM2 retarget: the SDK is located through MOD0/.dynamic (DT_SYMTAB/DT_STRTAB/DT_HASH) instead of the
section headers, and every imported OBJECT the SDK defines is extracted (not just nn::util/nn::hid).
"""
import struct, os

SDK = os.environ['RECOMP_SDK_ELF']
d = open(SDK, 'rb').read()
OFF = 0x1000

# .dynsym/.dynstr/.dynhash through MOD0 (its fields are module offsets relative to MOD0 itself)
mod0 = d.find(b'MOD0', OFF, OFF + 0x1000)
dyn_off = (mod0 - OFF) + struct.unpack_from('<i', d, mod0 + 4)[0]
dyn, o = {}, OFF + dyn_off
while True:
    tag, val = struct.unpack_from('<qQ', d, o)
    o += 16
    if tag == 0:
        break
    dyn.setdefault(tag, val)
sym_off = OFF + dyn[6]                                    # DT_SYMTAB
str_off = OFF + dyn[5]                                    # DT_STRTAB
nsym = struct.unpack_from('<I', d, OFF + dyn[4] + 4)[0]   # DT_HASH nchain


def cstr(off):
    return d[off:d.index(b'\0', off)].decode('latin-1')


syms = {}
for i in range(nsym):
    name_off, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', d, sym_off + i * 24)
    if shndx and (info & 0xf) == 1:                       # defined OBJECT
        syms[cstr(str_off + name_off)] = (value, size)

# MM2: todo dado (OBJECT) que o jogo importa e o sdk.elf define
wanted = [l.strip() for l in open('imports_all.txt') if l.strip()]
out, found = [], []
for name in wanted:
    if name in syms and 0 < syms[name][1] <= 1 << 20:
        value, size = syms[name]
        found.append((name, d[OFF + value:OFF + value + size]))
with open('sdkdata.c', 'w') as f:
    f.write('/* generated by gen_sdkdata.py from the real sdk module -- do not edit */\n#include "hostrt.h"\n\n')
    for k, (name, data) in enumerate(found):
        f.write('static const unsigned char d%d[] = {%s};\n' % (k, ','.join(str(b) for b in data)))
    f.write('\nconst SdkData sdk_data[] = {\n')
    for k, (name, data) in enumerate(found):
        f.write('  { "%s", d%d, %d },\n' % (name, k, len(data)))
    f.write('};\nconst int sdk_data_count = %d;\n' % len(found))
for name, data in found:
    print('%6d  %s' % (len(data), name))
print('%d data symbols extracted' % len(found))
